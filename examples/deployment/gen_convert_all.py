"""Write convert_all.sh for every exported run in a results folder.

The job container (docker/run.sh -- qairt-env, docs/modules/20261019-MOD-DockerEnv.md)
or any other machine with the QAIRT SDK runs the generated script from the results root
and gets one final quantized DLC per run, named like
BicubicPP_EO_640x360_x2_v3.dlc, with intermediates confined to a temp dir. The
DLC is prepared offline for HTP (snpe-dlc-graph-prepare), so the device loads
the cached graph instead of compiling it at start-up.

A run is a folder x<scale>_<eo|ir>[_1024] holding qat/qat_model.onnx and
qat/qat_model.encodings; a run missing either is left out with a warning.
Tensor names and the input size come from that run's own qat_model.onnx (the
x4 two-stage head exports a different graph from x2/x3), and the weight
bitwidth from its encodings, so W16 runs get --restrict_quantization_steps.
A conversion that fails does not abort the batch -- the remaining runs still
convert and the failures are listed at the end, with a non-zero exit.

    python3 examples/deployment/gen_convert_all.py <export_root> [--scales 3 4] [--domains ir]
"""
import argparse
import json
import os
import re
import sys

import onnx

DEFAULT_VERSION = "v3"

RUN_RE = re.compile(r"x(\d)_(eo|ir)(_1024)?$")


def convertible(root, run):
    """Whether the conversion could run right now: both artifacts present."""
    qat = os.path.join(root, run, "qat")
    return all(os.path.isfile(os.path.join(qat, f))
               for f in ("qat_model.onnx", "qat_model.encodings"))


def read_graph(root, run, warnings):
    """(in_name, out_name, w, h) from a run's exported ONNX, or None if it cannot be read."""
    onnx_path = os.path.join(root, run, "qat", "qat_model.onnx")
    if not os.path.isfile(onnx_path):
        return None
    try:
        g = onnx.load(onnx_path).graph
    except Exception as exc:  # truncated or corrupt export must not kill the run
        warnings.append(f"{run}: qat_model.onnx 를 읽을 수 없음 "
                        f"({exc.__class__.__name__}) -- 빠짐")
        return None
    dims = [d.dim_value for d in g.input[0].type.tensor_type.shape.dim]  # NCHW
    return g.input[0].name, g.output[0].name, dims[3], dims[2]


def collect(root, version=DEFAULT_VERSION, scales=None, domains=("eo", "ir")):
    """Every exported run under root, as (entries, warnings).

    An entry is (run, in_name, out_name, dlc). Only runs with both artifacts are
    listed, and every name comes from the run's own ONNX: a run is never filled
    in from another run's graph or from a table of expected sizes.
    """
    warnings = []
    entries = []
    for run in sorted(os.listdir(root)):
        m = RUN_RE.match(run)
        if not m:
            continue
        scale, domain = int(m.group(1)), m.group(2)
        if (scales and scale not in scales) or domain not in domains:
            continue
        if not convertible(root, run):
            warnings.append(f"{run}: qat_model.onnx 와 qat_model.encodings 가 다 있지 않음 -- 빠짐")
            continue
        graph = read_graph(root, run, warnings)
        if graph is None:
            continue
        in_name, out_name, w, h = graph
        entries.append((run, in_name, out_name, f"BicubicPP_{domain.upper()}_{w}x{h}_x{scale}_{version}.dlc"))

    # Two runs of the same domain, scale and input size land on one filename
    # (a hand-run export at another size can), and the second conversion would
    # quietly destroy the first one's DLC.
    by_dlc = {}
    for run, _, _, dlc in entries:
        by_dlc.setdefault(dlc, []).append(run)
    for dlc, runs_ in sorted(by_dlc.items()):
        if len(runs_) > 1:
            warnings.append(f"이름 충돌: {' / '.join(runs_)} 가 모두 {dlc} 로 갑니다 "
                            f"-- 스크립트가 두 번째부터 거부합니다")
    return entries, warnings


def param_bitwidth(run, root="."):
    """QAT 가 남긴 encodings 에서 가중치 비트폭을 읽는다.

    비트폭은 사람이 런마다 기억할 것이 아니라 산출물에 적혀 있다: AIMET 이
    quantizer_args.param_bitwidth 를 기록하므로, 거기서 읽으면 W8 과 W16 런이
    한 폴더에 섞여 있어도 각자 맞는 quantizer 옵션이 붙는다.
    """
    path = os.path.join(root, run, "qat", "qat_model.encodings")
    # collect() lists only runs whose encodings exist, so the
    # file exists. If it cannot be read anyway, that is a broken export, not
    # a W8 run -- defaulting to 8 here would drop the W16 quantizer flag and
    # ship a silently clipped DLC.
    with open(path, encoding="utf-8") as fh:
        args = json.load(fh).get("quantizer_args", {})
    if "param_bitwidth" not in args:
        raise ValueError(f"{path}: quantizer_args.param_bitwidth 없음 -- export 가 깨졌다")
    return int(args["param_bitwidth"])

def script_lines(entries, root=".", htp_socs="qcs8550", output_layer="final_act"):
    lines = [
        "#!/bin/bash",
        "# Generated by examples/deployment/gen_convert_all.py -- run on the machine with the QAIRT SDK.",
        "# Produces only the final quantized, HTP-prepared DLCs in this directory.",
        "# Runs whose QAT has not finished are reported and skipped, so this script",
        "# can be rerun as the chain fills them in.",
        'cd "$(dirname "$0")" || exit 1',
        'TMP=$(mktemp -d) || { echo "mktemp 실패"; exit 1; }',
        'case "$TMP" in /*) ;; *) echo "mktemp 가 이상한 경로를 반환: $TMP"; exit 1;; esac',
        "trap 'rm -rf \"$TMP\"' EXIT",
        'MADE=0; SKIPPED=0; FAILED=""; PRODUCED=""',
        "",
        "convert() {  # run in_name out_name dlc [param_bitwidth]",
        '    run=$1; in_name=$2; out_name=$3; dlc=$4; bw=${5:-8}',
        '    # 16bit 가중치는 Hexagon 이 표현할 수 있는 범위가 0x8000~0x7F7F 로 좁다.',
        '    # 두 값은 공백으로 이어진 ONE argument 여야 한다 -- 배열로 넘겨야',
        '    # 셸이 쪼개지 않는다. 문자열로 넘기면 따옴표가 값에 섞여 들어간다.',
        '    if [ "$bw" -ge 16 ]; then',
        '        QSTEPS=(--restrict_quantization_steps "-0x8000 0x7F7F")',
        '    else',
        '        QSTEPS=()',
        '    fi',
        '    if [ ! -f "$run/qat/qat_model.onnx" ] || [ ! -f "$run/qat/qat_model.encodings" ]; then',
        '        echo "=== $run: qat_model.onnx/encodings 없음 -> 건너뜀"',
        '        SKIPPED=$((SKIPPED + 1)); return 0',
        "    fi",
        '    case " $PRODUCED " in *" $dlc "*)',
        '        echo "!!! $run: $dlc 는 이번 실행에서 이미 만들어졌습니다 -> 덮어쓰지 않고 중단"',
        '        FAILED="$FAILED $run"; return 0;; esac',
        '    echo "=== $run -> $dlc ==="',
        "    # Every stage writes into $TMP; the deploy filename is only ever",
        "    # touched by the final mv, so a failure cannot leave a half-written",
        "    # DLC sitting under the name the device loads.",
        "    # graph-prepare stores the HTP-compiled graph in the DLC, so the device",
        "    # skips online prepare at load (owner-measured 2026-10-07: less CMA).",
        "    # The cache only matches a runtime asking for the same outputs, so the",
        "    # layer must be the one gst passes to qtimlsnpe layers=. A failed",
        "    # prepare fails the run rather than shipping an unprepared DLC.",
        "    if qairt-converter \\",
        '            --input_network "$run/qat/qat_model.onnx" \\',
        '            --quantization_overrides "$run/qat/qat_model.encodings" \\',
        '            --output_path "$TMP/$run.dlc" \\',
        '            --source_model_input_layout "$in_name" NCHW --desired_input_layout "$in_name" NHWC \\',
        '            --source_model_output_layout "$out_name" NCHW --desired_output_layout "$out_name" NHWC \\',
        '        && qairt-quantizer --input_dlc "$TMP/$run.dlc" --output_dlc "$TMP/$run.q.dlc" --float_fallback "${QSTEPS[@]}" \\',
        '        && snpe-dlc-graph-prepare --input_dlc "$TMP/$run.q.dlc" --output_dlc "$TMP/$run.htp.dlc" \\',
        f'            --htp_socs {htp_socs} --set_output_layers {output_layer} \\',
        '        && mv -f "$TMP/$run.htp.dlc" "$dlc"; then',
        "        MADE=$((MADE + 1))",
        '        PRODUCED="$PRODUCED $dlc"',
        "    else",
        '        echo "!!! $run 변환 실패"',
        '        [ -f "$dlc" ] && echo "    ($dlc 는 이전 실행에서 남은 파일입니다)"',
        '        FAILED="$FAILED $run"',
        "    fi",
        "}",
        "",
    ]
    for run, in_name, out_name, dlc in entries:
        # The bitwidth is read now, from the run's encodings: a W16 line without
        # it would convert without --restrict_quantization_steps, and Hexagon then
        # clips the 16-bit weights and reports success.
        bw = param_bitwidth(run, root)
        if bw >= 16:
            lines.append(f"convert {run} {in_name} {out_name} {dlc} {bw}")
        else:
            lines.append(f"convert {run} {in_name} {out_name} {dlc}")
    lines += [
        "",
        'echo ""',
        'echo "생성 $MADE개 / 건너뜀 $SKIPPED개"',
        'if [ -n "$FAILED" ]; then echo "실패:$FAILED"; fi',
        'ls -la ./*.dlc 2>/dev/null || echo "(생성된 DLC 없음)"',
        '[ -z "$FAILED" ]',
    ]
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", help="export 런 폴더(x<s>_<eo|ir>[_1024]/qat/)가 있는 results 폴더")
    ap.add_argument("--version", default=DEFAULT_VERSION,
                    help="DLC 파일명에 들어갈 버전 (기본 %(default)s)")
    ap.add_argument("--scales", type=int, nargs="*", default=None,
                    help="이 스케일만 다룬다 (기본: 2 3 4 전부)")
    ap.add_argument("--domains", nargs="*", default=["eo", "ir"], choices=["eo", "ir"],
                    help="이 도메인만 다룬다 (기본: eo ir)")
    ap.add_argument("--htp_socs", default="qcs8550",
                    help="snpe-dlc-graph-prepare 대상 SoC (기본 %(default)s)")
    ap.add_argument("--output_layer", default="final_act",
                    help="HTP 캐시의 출력 레이어, gst qtimlsnpe layers= 와 같아야 함 (기본 %(default)s)")
    args = ap.parse_args()

    if not os.path.isdir(args.root):
        print(f"no such results root: {args.root}")
        return 1
    entries, warnings = collect(args.root, args.version, args.scales, tuple(args.domains))
    if not entries:
        print(f"no runs to convert under {args.root}")
        for w in warnings:
            print(f"  ! {w}")
        return 1

    out = os.path.join(args.root, "convert_all.sh")
    if os.path.exists(out):
        print(f"{out} already exists -- move it away first (it may be the record of a shipped conversion)")
        return 1
    # Build the text first: a broken encodings file raises here, and must not leave an
    # empty convert_all.sh behind that the check above would then refuse to replace.
    text = "\n".join(script_lines(entries, args.root, args.htp_socs, args.output_layer)) + "\n"
    with open(out, "x", encoding="utf-8") as fh:
        fh.write(text)
    os.chmod(out, 0o755)

    print(f"{out}: {len(entries)} runs")
    for run, i, o, dlc in entries:
        print(f"  {run:<12} in={i:<6} out={o:<4} -> {dlc}")
    for w in warnings:
        print(f"  ! {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
