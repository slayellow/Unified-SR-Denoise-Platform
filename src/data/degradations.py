# Builds (LR, target) pairs that look like the EO camera's own output: optics
# blur -> sensor noise after the camera's NR -> the camera's brightness-dependent
# sharpening on luma -> NV12 (4:2:0, 8-bit). camera_model.target picks what the
# denoiser must reproduce: 'camera' = the same path without the noise (keeps the
# camera's sharpening), 'optics' = the blurred source before the ISP, 'source' =
# the clean input image (full restoration). Optional sparse defects go into the LR
# only: fixed hot pixels before sharpening (so they get the camera's dark ring) and,
# per noise mode, isolated impulses after it. All values are fitted to the 2026-10-08
# chart captures; see docs/modules/20261008-MOD-CameraModel.md and
# docs/CONFIG_RATIONALE.md section 14. Units are BT.601 limited-range DN, the
# units the camera's NV12 output was measured in.

_CAMERA_REQUIRED = ('optics_sigma', 'noise_scale', 'gain_jitter', 'noise_modes', 'sharpen')
_SHARPEN_REQUIRED = ('kernel', 'brightness_sigma', 'brightness_y', 'brightness_gain', 'gain_pos', 'gain_neg')
_MODE_REQUIRED = ('name', 'prob', 'nps_bands', 'luma_nps', 'luma_nlf', 'chroma_nps', 'chroma_sd')
_CAMERA_TARGETS = ('camera', 'optics', 'source')


def _require(cfg, keys, where):
    missing = [k for k in keys if k not in cfg]
    if missing:
        raise ValueError(f"camera_model: {where} is missing {', '.join(missing)}")


def _check_range(value, key, low=None):
    if len(value) != 2 or value[0] > value[1] or (low is not None and value[0] < low):
        raise ValueError(f"camera_model: {key} must be [min, max] with min <= max"
                         + (f" and min >= {low}" if low is not None else "") + f", got {value}")


def _check_kernel(k, key):
    k = np.asarray(k, dtype=np.float64)
    if k.ndim != 2 or k.shape[0] != k.shape[1] or k.shape[0] % 2 == 0:
        raise ValueError(f"camera_model: {key} must be square with odd size, got shape {k.shape}")


def validate_camera_model_cfg(cfg: dict) -> None:
    """Check a camera_model config block; raise ValueError naming the first bad key."""
    _require(cfg, _CAMERA_REQUIRED, 'camera_model')
    _check_range(cfg['optics_sigma'], 'optics_sigma', low=0.0)
    _check_range(cfg['noise_scale'], 'noise_scale', low=0.0)
    if cfg['noise_scale'][0] == 0 and cfg['noise_scale'][1] > 0:
        raise ValueError("camera_model: noise_scale is sampled log-uniformly, so min must be > 0 "
                         f"(or [0, 0] for noise-free pairs), got {cfg['noise_scale']}")
    if not 0.0 <= cfg['gain_jitter'] < 1.0:
        raise ValueError(f"camera_model: gain_jitter must be in [0, 1), got {cfg['gain_jitter']}")
    if not 0.0 <= cfg.get('prob', 1.0) <= 1.0:
        raise ValueError(f"camera_model: prob must be in [0, 1], got {cfg.get('prob')}")
    if cfg.get('target', 'camera') not in _CAMERA_TARGETS:
        raise ValueError(f"camera_model: target must be one of {', '.join(_CAMERA_TARGETS)}, got {cfg.get('target')}")

    sh = cfg['sharpen']
    _require(sh, _SHARPEN_REQUIRED, 'sharpen')
    _check_kernel(sh['kernel'], 'sharpen.kernel')
    by, bg = np.asarray(sh['brightness_y'], float), np.asarray(sh['brightness_gain'], float)
    if by.ndim != 1 or len(by) < 2 or len(by) != len(bg) or np.any(np.diff(by) <= 0):
        raise ValueError("camera_model: sharpen.brightness_y must be strictly increasing and as long as brightness_gain")
    if sh['brightness_sigma'] <= 0:
        raise ValueError(f"camera_model: sharpen.brightness_sigma must be > 0, got {sh['brightness_sigma']}")
    if sh['gain_pos'] < 0 or sh['gain_neg'] < 0:
        raise ValueError("camera_model: sharpen.gain_pos and gain_neg must be >= 0")

    hot = cfg.get('hot_pixels')
    if hot is not None:
        _require(hot, ('density', 'amplitude', 'footprint'), 'hot_pixels')
        _check_range(hot['density'], 'hot_pixels.density', low=0.0)
        _check_range(hot['amplitude'], 'hot_pixels.amplitude', low=0.0)
        _check_kernel(hot['footprint'], 'hot_pixels.footprint')

    modes = cfg['noise_modes']
    if not modes:
        raise ValueError("camera_model: noise_modes is empty")
    for i, m in enumerate(modes):
        _require(m, _MODE_REQUIRED, f'noise_modes[{i}]')
        bands = np.asarray(m['nps_bands'], float)
        if bands.ndim != 1 or len(bands) < 2 or np.any(np.diff(bands) <= 0):
            raise ValueError(f"camera_model: noise_modes[{i}].nps_bands must be strictly increasing")
        for key in ('luma_nps', 'chroma_nps'):
            v = np.asarray(m[key], float)
            if v.shape != bands.shape or np.any(v <= 0):
                raise ValueError(f"camera_model: noise_modes[{i}].{key} must be positive and as long as nps_bands")
        nlf = np.asarray(m['luma_nlf'], float)
        if nlf.ndim != 2 or nlf.shape[1] != 2 or len(nlf) < 2 or np.any(np.diff(nlf[:, 0]) <= 0) or np.any(nlf[:, 1] < 0):
            raise ValueError(f"camera_model: noise_modes[{i}].luma_nlf must be [[Y, sd], ...] with increasing Y and sd >= 0")
        if len(m['chroma_sd']) != 2 or min(m['chroma_sd']) < 0:
            raise ValueError(f"camera_model: noise_modes[{i}].chroma_sd must be [sd_cb, sd_cr] >= 0")
        imp = m.get('impulses')
        if imp is not None:
            _require(imp, ('density', 'amplitude', 'bright_share'), f'noise_modes[{i}].impulses')
            _check_range(imp['density'], f'noise_modes[{i}].impulses.density', low=0.0)
            _check_range(imp['amplitude'], f'noise_modes[{i}].impulses.amplitude', low=0.0)
            if not 0.0 <= imp['bright_share'] <= 1.0:
                raise ValueError(f"camera_model: noise_modes[{i}].impulses.bright_share must be in [0, 1], got {imp['bright_share']}")
    if any(float(m['prob']) < 0 for m in modes):
        raise ValueError("camera_model: noise_modes prob must be >= 0")
    total = sum(float(m['prob']) for m in modes)
    if abs(total - 1.0) > 1e-6:
        raise ValueError(f"camera_model: noise_modes prob must sum to 1, got {total}")


def bgr_to_ycbcr601(img):
    """float BGR in [0, 255] -> float YCbCr, BT.601 limited range (Y 16-235, C 16-240)."""
    b, g, r = img[..., 0], img[..., 1], img[..., 2]
    y = 16.0 + (65.481 * r + 128.553 * g + 24.966 * b) / 255.0
    cb = 128.0 + (-37.797 * r - 74.203 * g + 112.0 * b) / 255.0
    cr = 128.0 + (112.0 * r - 93.786 * g - 18.214 * b) / 255.0
    return np.stack([y, cb, cr], axis=-1).astype(np.float32)


def ycbcr601_to_bgr(ycc):
    """float YCbCr (BT.601 limited range) -> float BGR in [0, 255], not clipped."""
    y = (ycc[..., 0] - 16.0) * (255.0 / 219.0)
    cb = (ycc[..., 1] - 128.0) * (255.0 / 224.0)
    cr = (ycc[..., 2] - 128.0) * (255.0 / 224.0)
    r = y + 1.402 * cr
    g = y - 0.344136 * cb - 0.714136 * cr
    b = y + 1.772 * cb
    return np.stack([b, g, r], axis=-1).astype(np.float32)


def camera_sharpen(y, sharpen_cfg, gain_scale=1.0):
    """Peaking on a float luma plane (limited-range DN): y + b(local brightness) * (+/- weighted K * y)."""
    k = np.asarray(sharpen_cfg['kernel'], dtype=np.float32)
    d = cv2.filter2D(y, cv2.CV_32F, k, borderType=cv2.BORDER_REPLICATE)
    ym = cv2.GaussianBlur(y, (0, 0), float(sharpen_cfg['brightness_sigma']), borderType=cv2.BORDER_REPLICATE)
    b = np.interp(ym, sharpen_cfg['brightness_y'], sharpen_cfg['brightness_gain']).astype(np.float32)
    boost = float(sharpen_cfg['gain_pos']) * np.maximum(d, 0) - float(sharpen_cfg['gain_neg']) * np.maximum(-d, 0)
    return (y + gain_scale * b * boost).astype(np.float32)


def shaped_noise(h, w, bands, nps, rng):
    """Unit-variance Gaussian noise of size (h, w) whose power spectrum follows a radial profile (cycles/px)."""
    if h * w < 2:
        return np.zeros((h, w), dtype=np.float32)  # a single sample has no spectrum to shape
    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.fftfreq(w)[None, :]
    amp = np.sqrt(np.interp(np.hypot(fy, fx), bands, nps))
    n = np.fft.ifft2(np.fft.fft2(rng.standard_normal((h, w))) * amp).real
    return (n / max(float(n.std()), 1e-12)).astype(np.float32)


def camera_luma_noise(y, mode, scale, rng):
    """Pre-sharpening luma noise for a float Y plane: spectrum-shaped, sd from the mode's NLF at the local brightness."""
    nlf = np.asarray(mode['luma_nlf'], dtype=np.float32)
    y_local = cv2.GaussianBlur(y, (0, 0), 2.0, borderType=cv2.BORDER_REPLICATE)
    sd = np.interp(y_local, nlf[:, 0], nlf[:, 1]).astype(np.float32) * scale
    return sd * shaped_noise(y.shape[0], y.shape[1], mode['nps_bands'], mode['luma_nps'], rng)


def camera_chroma_noise(hh, hw, mode, scale, rng):
    """(Cb, Cr) noise for the half-resolution chroma planes of NV12."""
    sd_cb, sd_cr = (float(v) * scale for v in mode['chroma_sd'])
    n_cb = sd_cb * shaped_noise(hh, hw, mode['nps_bands'], mode['chroma_nps'], rng)
    n_cr = sd_cr * shaped_noise(hh, hw, mode['nps_bands'], mode['chroma_nps'], rng)
    return n_cb, n_cr


def sparse_impulses(h, w, density, amplitude, rng, bright_share=1.0):
    """Float (h, w) plane of isolated impulses: Poisson count at density [min, max] per Mpx, |value| ~ U(amplitude) DN."""
    out = np.zeros((h, w), dtype=np.float32)
    n = rng.poisson(rng.uniform(*density) * h * w / 1e6)
    ys, xs = rng.integers(0, h, n), rng.integers(0, w, n)
    amp = rng.uniform(*amplitude, n) * np.where(rng.random(n) < bright_share, 1.0, -1.0)
    np.add.at(out, (ys, xs), amp.astype(np.float32))
    return out


def _to_nv12_bgr(y, cb_half, cr_half, h, w):
    """Quantise Y/Cb/Cr to 8 bit as NV12 does, upsample chroma, return uint8 BGR."""
    y = np.clip(np.round(y), 0, 255)
    cb = cv2.resize(np.clip(np.round(cb_half), 0, 255), (w, h), interpolation=cv2.INTER_LINEAR)
    cr = cv2.resize(np.clip(np.round(cr_half), 0, 255), (w, h), interpolation=cv2.INTER_LINEAR)
    bgr = ycbcr601_to_bgr(np.stack([y, cb, cr], axis=-1))
    return np.clip(np.round(bgr), 0, 255).astype(np.uint8)


def apply_camera_model(img_bgr, cfg, rng=None):
    """uint8 BGR patch -> (lr, target) uint8 BGR pair through the fitted camera model; target per cfg['target']."""
    if rng is None:
        rng = np.random.default_rng(np.random.randint(0, 2 ** 31 - 1))
    h, w = img_bgr.shape[:2]
    hh, hw = (h + 1) // 2, (w + 1) // 2

    sigma = rng.uniform(*cfg['optics_sigma'])
    modes = cfg['noise_modes']
    probs = np.array([float(m['prob']) for m in modes])
    mode = modes[rng.choice(len(modes), p=probs / probs.sum())]
    lo, hi = cfg['noise_scale']
    scale = 0.0 if hi <= 0 else (lo if lo == hi else float(np.exp(rng.uniform(np.log(lo), np.log(hi)))))
    jitter = float(cfg['gain_jitter'])
    gain = rng.uniform(1.0 - jitter, 1.0 + jitter)

    img = img_bgr.astype(np.float32)
    if sigma > 0:
        img = cv2.GaussianBlur(img, (0, 0), sigma, borderType=cv2.BORDER_REFLECT)
    ycc = bgr_to_ycbcr601(img)
    y = ycc[..., 0]
    cb_half = cv2.resize(ycc[..., 1], (hw, hh), interpolation=cv2.INTER_AREA)
    cr_half = cv2.resize(ycc[..., 2], (hw, hh), interpolation=cv2.INTER_AREA)

    sh = cfg['sharpen']
    camera_clean = _to_nv12_bgr(camera_sharpen(y, sh, gain), cb_half, cr_half, h, w)
    target_mode = cfg.get('target', 'camera')
    if target_mode == 'source':
        target = img_bgr.copy()
    elif target_mode == 'optics':
        target = np.clip(np.round(img), 0, 255).astype(np.uint8)
    else:
        target = camera_clean
    if scale == 0.0:
        return camera_clean.copy(), target

    y_noisy = y + camera_luma_noise(y, mode, scale, rng)
    n_cb, n_cr = camera_chroma_noise(hh, hw, mode, scale, rng)
    hot = cfg.get('hot_pixels')
    if hot:
        defects = sparse_impulses(h, w, hot['density'], hot['amplitude'], rng)
        footprint = np.asarray(hot['footprint'], dtype=np.float32)
        y_noisy = y_noisy + cv2.filter2D(defects, cv2.CV_32F, footprint, borderType=cv2.BORDER_CONSTANT)
    y_lr = camera_sharpen(y_noisy, sh, gain)
    imp = mode.get('impulses')
    if imp:
        y_lr = y_lr + sparse_impulses(h, w, imp['density'], imp['amplitude'], rng, float(imp['bright_share']))
    lr = _to_nv12_bgr(y_lr, cb_half + n_cb, cr_half + n_cr, h, w)
    return lr, target
